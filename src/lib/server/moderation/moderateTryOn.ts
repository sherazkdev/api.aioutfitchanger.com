import type { NormalizedImageInput } from "../bfl/normalizeImageInput";
import { moderateImageInput } from "./moderateImage";
import { moderateText } from "./moderateText";

export type TryOnModerationFailure = {
  httpStatus: 422 | 503;
  code: "MODERATION_BLOCKED" | "VALIDATION" | "MODERATION_UNAVAILABLE";
  message: string;
};

const POLICY_MESSAGE = "This request is not allowed under our content policy.";

/**
 * Pre-provider moderation: prompt text + structural image checks (format/size).
 * No external image-safety vendor.
 */
export async function moderateTryOnRequest(params: {
  promptTexts: (string | null | undefined)[];
  person: NormalizedImageInput;
  garment?: NormalizedImageInput | null;
}): Promise<TryOnModerationFailure | null> {
  for (const text of params.promptTexts) {
    const t = moderateText(text);
    if (!t.ok) {
      return {
        httpStatus: 422,
        code: "MODERATION_BLOCKED",
        message: POLICY_MESSAGE,
      };
    }
  }

  const personCheck = moderateImageInput(params.person, "PERSON");
  if (!personCheck.ok) {
    return {
      httpStatus: 422,
      code: personCheck.code,
      message: personCheck.message,
    };
  }

  if (params.garment) {
    const garmentCheck = moderateImageInput(params.garment, "GARMENT");
    if (!garmentCheck.ok) {
      return {
        httpStatus: 422,
        code: garmentCheck.code,
        message: garmentCheck.message,
      };
    }
  }

  return null;
}

export function isProviderModerationFailure(message: string | null | undefined): boolean {
  if (!message) return false;
  const m = message.toLowerCase();
  return m.includes("request moderated") || m.includes("moderation") || m === "moderation_blocked";
}

/** Structural-only check for generated bytes (format/size). Not safety/NSFW. */
export function validateGeneratedImageStructure(buffer: Buffer): TryOnModerationFailure | null {
  if (!buffer || buffer.length < 200) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image is too small or invalid",
    };
  }
  if (buffer.length > 12 * 1024 * 1024) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image exceeds size limit",
    };
  }
  const isJpeg = buffer[0] === 0xff && buffer[1] === 0xd8;
  const isPng = buffer[0] === 0x89 && buffer[1] === 0x50;
  const isWebp =
    buffer.length > 12 &&
    buffer[0] === 0x52 &&
    buffer[1] === 0x49 &&
    buffer[2] === 0x46 &&
    buffer[3] === 0x46 &&
    buffer[8] === 0x57 &&
    buffer[9] === 0x45 &&
    buffer[10] === 0x42 &&
    buffer[11] === 0x50;
  if (!isJpeg && !isPng && !isWebp) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image must be JPEG, PNG, or WebP",
    };
  }
  return null;
}

/**
 * Post-provider structural validation before watermark/persist.
 * Kept async for call-site compatibility.
 */
export async function moderateGeneratedResultBuffer(
  buffer: Buffer
): Promise<TryOnModerationFailure | null> {
  return validateGeneratedImageStructure(buffer);
}

