import { createHash } from "crypto";
import type { NormalizedImageInput } from "../bfl/normalizeImageInput";
import { moderateImageInput } from "./moderateImage";
import { moderateText } from "./moderateText";
import {
  bufferFromDataUrlOrBase64,
  imageSafetyFailClosed,
  moderateImageSafety,
} from "./imageSafety";

export type TryOnModerationFailure = {
  httpStatus: 422 | 503;
  code: "MODERATION_BLOCKED" | "VALIDATION" | "MODERATION_UNAVAILABLE";
  message: string;
};

const POLICY_MESSAGE = "This request is not allowed under our content policy.";
const SERVICE_MESSAGE = "Content safety check is temporarily unavailable. Please try again.";

/** Per-request cache: avoid scanning the same buffer twice in one generate call. */
export type ImageSafetyRequestCache = Map<string, Awaited<ReturnType<typeof moderateImageSafety>>>;

function bufferFingerprint(buf: Buffer): string {
  // Request-local dedupe key only (not logged / not persisted as content).
  return createHash("sha256").update(buf).digest("hex");
}

async function runImageSafetyCached(
  buffer: Buffer,
  cache?: ImageSafetyRequestCache
): Promise<Awaited<ReturnType<typeof moderateImageSafety>>> {
  const key = bufferFingerprint(buffer);
  if (cache?.has(key)) return cache.get(key)!;
  const outcome = await moderateImageSafety(buffer);
  cache?.set(key, outcome);
  return outcome;
}

function safetyOutcomeToFailure(
  outcome: Awaited<ReturnType<typeof moderateImageSafety>>
): TryOnModerationFailure | null {
  if (outcome.status === "disabled" || outcome.status === "allowed") return null;
  if (outcome.status === "blocked") {
    return {
      httpStatus: 422,
      code: "MODERATION_BLOCKED",
      message: POLICY_MESSAGE,
    };
  }
  // error
  if (outcome.failClosed || imageSafetyFailClosed()) {
    return {
      httpStatus: 503,
      code: "MODERATION_UNAVAILABLE",
      message: SERVICE_MESSAGE,
    };
  }
  return null;
}

/**
 * Pre-provider moderation:
 * prompt → structural image checks → real image-safety (SafeSearch) for person/garment.
 */
export async function moderateTryOnRequest(params: {
  promptTexts: (string | null | undefined)[];
  person: NormalizedImageInput;
  garment?: NormalizedImageInput | null;
  safetyCache?: ImageSafetyRequestCache;
}): Promise<TryOnModerationFailure | null> {
  for (const text of params.promptTexts) {
    const t = moderateText(text);
    if (!t.ok) {
      return {
        httpStatus: 422,
        code: "MODERATION_BLOCKED",
        message: POLICY_MESSAGE,
      };
    }
  }

  const personCheck = moderateImageInput(params.person, "PERSON");
  if (!personCheck.ok) {
    return {
      httpStatus: 422,
      code: personCheck.code,
      message: personCheck.message,
    };
  }

  const personBuf = bufferFromDataUrlOrBase64(params.person.dataUrl);
  if (!personBuf) {
    return { httpStatus: 422, code: "VALIDATION", message: "PERSON image is invalid" };
  }
  const personSafety = await runImageSafetyCached(personBuf, params.safetyCache);
  const personFail = safetyOutcomeToFailure(personSafety);
  if (personFail) return personFail;

  if (params.garment) {
    const garmentCheck = moderateImageInput(params.garment, "GARMENT");
    if (!garmentCheck.ok) {
      return {
        httpStatus: 422,
        code: garmentCheck.code,
        message: garmentCheck.message,
      };
    }
    const garmentBuf = bufferFromDataUrlOrBase64(params.garment.dataUrl);
    if (!garmentBuf) {
      return { httpStatus: 422, code: "VALIDATION", message: "GARMENT image is invalid" };
    }
    const garmentSafety = await runImageSafetyCached(garmentBuf, params.safetyCache);
    const garmentFail = safetyOutcomeToFailure(garmentSafety);
    if (garmentFail) return garmentFail;
  }

  return null;
}

export function isProviderModerationFailure(message: string | null | undefined): boolean {
  if (!message) return false;
  const m = message.toLowerCase();
  return m.includes("request moderated") || m.includes("moderation") || m === "moderation_blocked";
}

/** Structural-only check for generated bytes (format/size). Not safety. */
export function validateGeneratedImageStructure(buffer: Buffer): TryOnModerationFailure | null {
  if (!buffer || buffer.length < 200) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image is too small or invalid",
    };
  }
  if (buffer.length > 12 * 1024 * 1024) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image exceeds size limit",
    };
  }
  const isJpeg = buffer[0] === 0xff && buffer[1] === 0xd8;
  const isPng = buffer[0] === 0x89 && buffer[1] === 0x50;
  const isWebp =
    buffer.length > 12 &&
    buffer[0] === 0x52 &&
    buffer[1] === 0x49 &&
    buffer[2] === 0x46 &&
    buffer[3] === 0x46 &&
    buffer[8] === 0x57 &&
    buffer[9] === 0x45 &&
    buffer[10] === 0x42 &&
    buffer[11] === 0x50;
  if (!isJpeg && !isPng && !isWebp) {
    return {
      httpStatus: 422,
      code: "VALIDATION",
      message: "Generated image must be JPEG, PNG, or WebP",
    };
  }
  return null;
}

/**
 * Post-provider: structure then real SafeSearch.
 * Throws OUTPUT_MODERATION_BLOCKED | OUTPUT_MODERATION_UNAVAILABLE for persist layer.
 */
export async function moderateGeneratedResultBuffer(
  buffer: Buffer,
  safetyCache?: ImageSafetyRequestCache
): Promise<TryOnModerationFailure | null> {
  const structural = validateGeneratedImageStructure(buffer);
  if (structural) return structural;

  const outcome = await runImageSafetyCached(buffer, safetyCache);
  return safetyOutcomeToFailure(outcome);
}

